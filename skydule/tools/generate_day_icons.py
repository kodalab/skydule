#!/usr/bin/env python3
"""Generates the dynamic app-icon set: one adaptive icon per (valid date, time of day) = 366 x 4 = 1,464.

Launchers can't draw an icon live, so every look has to exist ahead of time and the app switches between them
(see icons/DayIcon.kt). To keep the app small the icons are tiny vector files:
  - res/drawable/ic_dyn_bg_<period>.xml        4 sky backgrounds (dawn, day, dusk, night)
  - res/drawable/ic_dyn_fg_<period>_MM_DD.xml           1,464 foregrounds (per period, as the month is tinted): short month over the day number, as outlines
  - res/mipmap-anydpi/ic_dyn_<period>_MM_DD.xml  1,464 adaptive icons pairing a background with a foreground
  - the block between the markers in AndroidManifest.xml: a "DefaultIcon" alias plus one alias per icon.

Sky colours are parsed from ui/SkyBackground.kt (one source of truth) at a representative hour per period.
Keep PERIOD_HOURS in step with IconPeriod in icons/DayIcon.kt.

Run:  python3 tools/generate_day_icons.py        (needs: pip install fonttools)
"""
import calendar
import pathlib
import re
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKY_KT = ROOT / "app/src/main/java/com/example/gradule/ui/SkyBackground.kt"
RES = ROOT / "app/src/main/res"
MANIFEST = ROOT / "app/src/main/AndroidManifest.xml"
FONT = ROOT / "tools/fonts/IBMPlexSerif-Bold.ttf"

PERIODS = ["dawn", "day", "dusk", "night"]
PERIOD_HOURS = {"dawn": 6.5, "day": 11.0, "dusk": 18.5, "night": 22.0}   # which sky each period shows
MONTHS = ["JAN", "FEB", "MAR", "APR", "MAY", "JUN", "JUL", "AUG", "SEP", "OCT", "NOV", "DEC"]
MARK_BEGIN = "<!-- BEGIN icon aliases (generated by tools/generate_day_icons.py) -->"
MARK_END = "<!-- END icon aliases -->"

# Layout in a 512-unit square that is the visible icon; in the 108dp canvas it is the centre 72dp.
K, OFF = 72 / 512, 18
MONTH_SIZE, MONTH_CY = 0.17 * 512, 0.27 * 512
DAY_SIZE, DAY_CY = 0.52 * 512, 0.64 * 512
SHADOW = 0.02 * 512
MONTH_TINT = 0.80   # month = the sky's lightest colour mixed this far toward white (day number stays pure white)


def parse_sky_stops():
    text = SKY_KT.read_text(encoding="utf-8")
    pat = re.compile(r"SkyStop\(([\d.]+)f,\s*Color\(0xFF([0-9A-Fa-f]{6})\),\s*Color\(0xFF([0-9A-Fa-f]{6})\)\)")
    stops = [(float(h), tuple(int(t[i:i + 2], 16) for i in (0, 2, 4)), tuple(int(b[i:i + 2], 16) for i in (0, 2, 4)))
             for h, t, b in pat.findall(text)]
    if len(stops) < 2:
        sys.exit("Could not find sky stops in SkyBackground.kt")
    return stops


def lerp(a, b, t):
    return tuple(round(x + (y - x) * t) for x, y in zip(a, b))


def sky_colors(stops, hour):
    """Mirror of skyColors() in SkyBackground.kt."""
    idx = min(max(max(i for i, s in enumerate(stops) if s[0] <= hour), 0), len(stops) - 2)
    h0, t0, b0 = stops[idx]
    h1, t1, b1 = stops[idx + 1]
    t = min(max((hour - h0) / (h1 - h0), 0.0), 1.0)
    return lerp(t0, t1, t), lerp(b0, b1, t)


def hexc(c):
    return "#FF%02X%02X%02X" % c


class Text:
    def __init__(self):
        self.f = TTFont(str(FONT))
        self.gs = self.f.getGlyphSet()
        self.cmap = self.f.getBestCmap()
        self.hmtx = self.f["hmtx"]
        self.upm = self.f["head"].unitsPerEm
        self.cache = {}

    def path(self, text, size, cy, dy_units=0.0):
        """Path data (dp) for `text` centred horizontally at x=256 and vertically on its line box at `cy`."""
        key = (text, size, cy, dy_units)
        if key in self.cache:
            return self.cache[key]
        s = size / self.upm
        asc, desc = self.f["hhea"].ascent * s, -self.f["hhea"].descent * s
        width = sum(self.hmtx[self.cmap[ord(c)]][0] for c in text) * s
        x = 256 - width / 2
        baseline = cy + (asc - desc) / 2 + dy_units
        ntos = lambda v: ("%.2f" % v).rstrip("0").rstrip(".")
        out = []
        for ch in text:
            name = self.cmap[ord(ch)]
            pen = SVGPathPen(self.gs, ntos=ntos)
            self.gs[name].draw(TransformPen(pen, (s * K, 0, 0, -s * K, OFF + x * K, OFF + baseline * K)))
            out.append(pen.getCommands())
            x += self.hmtx[name][0] * s
        self.cache[key] = "".join(out)
        return self.cache[key]


def dates():
    for month in range(1, 13):
        for day in range(1, calendar.monthrange(2028, month)[1] + 1):   # 2028 is a leap year: includes 29 Feb
            yield month, day


def month_color(stops, period):
    """Lightest end of the period's sky, lifted toward white. Keep in step with IconPickerScreen's preview."""
    top, bottom = sky_colors(stops, PERIOD_HOURS[period])
    lum = lambda c: .2126 * c[0] + .7152 * c[1] + .0722 * c[2]
    light = top if lum(top) > lum(bottom) else bottom
    return tuple(round(v + (255 - v) * MONTH_TINT) for v in light)


def write_backgrounds(stops):
    for p in PERIODS:
        top, bottom = sky_colors(stops, PERIOD_HOURS[p])
        # A launcher shows the centre 72dp of the 108dp canvas, so the gradient covers exactly that part and the
        # margins above and below take the end colours.
        # One full-canvas vector: the gradient runs over the visible y=18..90 and clamps beyond it.
        (RES / f"drawable/ic_dyn_bg_{p}.xml").write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_day_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="54" android:startY="18" android:endX="54" android:endY="90"
                android:startColor="{hexc(top)}" android:endColor="{hexc(bottom)}" />
        </aapt:attr>
    </path>
</vector>
''', encoding="utf-8")


def write_icons(text, stops):
    (RES / "mipmap-anydpi").mkdir(parents=True, exist_ok=True)
    for old in list((RES / "drawable").glob("ic_dyn_fg_*.xml")) + list((RES / "mipmap-anydpi").glob("ic_dyn_*.xml")):
        old.unlink()
    n = 0
    for month, day in dates():
        label = MONTHS[month - 1]
        for p in PERIODS:
            fg = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_day_icons.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#46000000" android:pathData="{text.path(label, MONTH_SIZE, MONTH_CY, SHADOW)}" />
    <path android:fillColor="#46000000" android:pathData="{text.path(str(day), DAY_SIZE, DAY_CY, SHADOW)}" />
    <path android:fillColor="{hexc(month_color(stops, p))}" android:pathData="{text.path(label, MONTH_SIZE, MONTH_CY)}" />
    <path android:fillColor="#FFFFFFFF" android:pathData="{text.path(str(day), DAY_SIZE, DAY_CY)}" />
</vector>
'''
            (RES / f"drawable/ic_dyn_fg_{p}_{month:02d}_{day:02d}.xml").write_text(fg, encoding="utf-8")
            (RES / f"mipmap-anydpi/ic_dyn_{p}_{month:02d}_{day:02d}.xml").write_text(
                '<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                f'    <background android:drawable="@drawable/ic_dyn_bg_{p}" />\n'
                f'    <foreground android:drawable="@drawable/ic_dyn_fg_{p}_{month:02d}_{day:02d}" />\n'
                '</adaptive-icon>\n', encoding="utf-8")
            n += 1
    return n


def alias(name, icon, enabled):
    return "\n".join([
        "        <activity-alias",
        f'            android:name=".icons.{name}"',
        '            android:targetActivity=".MainActivity"',
        f'            android:enabled="{enabled}"',
        '            android:exported="true"',
        f'            android:icon="@mipmap/{icon}"',
        '            android:label="@string/app_name">',
        "            <intent-filter>",
        '                <action android:name="android.intent.action.MAIN" />',
        '                <category android:name="android.intent.category.LAUNCHER" />',
        "            </intent-filter>",
        "        </activity-alias>",
    ])


def write_manifest():
    # DefaultIcon is the one enabled alias out of the box. Dynamic aliases are A<period index>M<mm>D<dd>.
    parts = [MARK_BEGIN, alias("DefaultIcon", "ic_launcher", "true")]
    for month, day in dates():
        for i, p in enumerate(PERIODS):
            parts.append(alias(f"A{i}M{month:02d}D{day:02d}", f"ic_dyn_{p}_{month:02d}_{day:02d}", "false"))
    parts.append(f"        {MARK_END}")
    block = "\n".join(parts)
    text = MANIFEST.read_text(encoding="utf-8")
    old = re.compile(r"<!-- BEGIN (?:day-)?icon aliases.*?<!-- END (?:day-)?icon aliases -->", re.S)
    if old.search(text):
        text = old.sub(lambda _: block, text)
    else:
        text = text.replace("    </application>", "        " + block + "\n    </application>")
    MANIFEST.write_text(text, encoding="utf-8")


def main():
    stops = parse_sky_stops()
    write_backgrounds(stops)
    n = write_icons(Text(), stops)
    write_manifest()
    # Old fixed-sky PNGs are replaced by the vectors.
    for old in (RES / "mipmap-xxxhdpi").glob("ic_day_*.png"):
        old.unlink()
    print(f"Wrote {n} adaptive icons, {len(list(dates()))} foregrounds, 4 backgrounds, and updated {MANIFEST}")


if __name__ == "__main__":
    main()
