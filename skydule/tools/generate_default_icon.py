"""Builds the static launcher icon: "Skydule" in IBM Plex Serif Bold with a small sun, on the sunrise gradient.

Writes the adaptive-icon vectors (res/drawable/ic_launcher_{foreground,background}.xml) and the Play listing
icons (store/icon-512.png, icon-1024.png, icon-2048.png). The word is vector outlines, so the app icon is sharp
at any size. Run: python3 tools/generate_default_icon.py   (needs: pip install fonttools pillow)

Geometry is defined once in a 512-unit square that is the *visible* icon (what a launcher mask shows). In the
108dp adaptive canvas that square is the centre 72dp, so dp = 18 + u * 72/512.
"""
import os
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app/src/main/res")
FONT = os.path.join(ROOT, "tools/fonts/IBMPlexSerif-Bold.ttf")
WORD = "Skydule"

# Sunrise: blue sky, purple, orange glow.
STOPS = [(0.0, (0x1B, 0x2A, 0x6B)), (0.55, (0x6A, 0x3F, 0x9C)), (1.0, (0xF2, 0x94, 0x45))]
FONT_U = 0.16 * 512      # font size in units (16% of the icon)
WORD_CY = 0.57 * 512     # vertical centre of the text line box
SUN_R = 0.05 * 512
SUN_GAP = 0.10 * 512     # gap between the top of the word and the sun's centre line (as in the previews)
K = 72 / 512             # unit -> dp
OFF = 18                 # dp


def layout():
    """Returns (path commands in dp for the word, ink bounds in units, sun centre units)."""
    f = TTFont(FONT)
    gs, cmap, hmtx = f.getGlyphSet(), f.getBestCmap(), f["hmtx"]
    upm = f["head"].unitsPerEm
    s = FONT_U / upm
    asc, desc = f["hhea"].ascent * s, -f["hhea"].descent * s
    width = sum(hmtx[cmap[ord(c)]][0] for c in WORD) * s
    x0 = 256 - width / 2
    baseline = WORD_CY + (asc - desc) / 2          # same placement as a "middle" anchored line box
    pen_x = x0
    bounds = [1e9, 1e9, -1e9, -1e9]
    glyphs = []
    for c in WORD:
        name = cmap[ord(c)]
        bp = BoundsPen(gs)
        gs[name].draw(TransformPen(bp, (s, 0, 0, -s, pen_x, baseline)))
        if bp.bounds:
            b = bp.bounds
            bounds = [min(bounds[0], b[0]), min(bounds[1], b[1]), max(bounds[2], b[2]), max(bounds[3], b[3])]
        glyphs.append((name, pen_x))
        pen_x += hmtx[name][0] * s
    sun = (256, (bounds[1] + bounds[3]) / 2 - (bounds[3] - bounds[1]) / 2 - SUN_GAP)
    return f, gs, glyphs, s, baseline, bounds, sun


def word_path_dp(dy_dp=0.0):
    f, gs, glyphs, s, baseline, _, _ = layout()
    ntos = lambda v: ("%.2f" % v).rstrip("0").rstrip(".")
    out = []
    for name, x in glyphs:
        pen = SVGPathPen(gs, ntos=ntos)
        # unit space -> dp: scale by K and shift by OFF; font y is flipped.
        gs[name].draw(TransformPen(pen, (s * K, 0, 0, -s * K, OFF + x * K, OFF + baseline * K + dy_dp)))
        out.append(pen.getCommands())
    return "".join(out)


def hexc(c): return "#FF%02X%02X%02X" % c


def write_vectors():
    _, _, _, _, _, _, sun = layout()
    sx, sy, sr = OFF + sun[0] * K, OFF + sun[1] * K, SUN_R * K
    sun_path = f"M{sx - sr:.2f},{sy:.2f}a{sr:.2f},{sr:.2f} 0 1 1 {2 * sr:.2f},0a{sr:.2f},{sr:.2f} 0 1 1 -{2 * sr:.2f},0z"
    open(os.path.join(RES, "drawable/ic_launcher_foreground.xml"), "w").write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_default_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="#40000000" android:pathData="{word_path_dp(0.8)}" />
    <path android:fillColor="#FFFFFFFF" android:pathData="{word_path_dp()}" />
    <path android:pathData="{sun_path}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{sx:.2f}" android:startY="{sy - sr:.2f}"
                android:endX="{sx:.2f}" android:endY="{sy + sr:.2f}"
                android:startColor="#FFFFECAA" android:endColor="#FFFFA55A" />
        </aapt:attr>
    </path>
</vector>
''')
    top, mid, bot = STOPS[0][1], STOPS[1][1], STOPS[2][1]
    # A launcher shows only the middle 72dp of the 108dp canvas, but some launchers show a little more or less, so
    # the background is one full-canvas vector: the gradient runs over y=18..90 and clamps to its end colours
    # beyond that, so there is never an unpainted or mismatched edge.
    open(os.path.join(RES, "drawable/ic_launcher_background.xml"), "w").write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_default_icon.py: blue sky into purple into a low orange glow. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="54" android:startY="18" android:endX="54" android:endY="90"
                android:startColor="{hexc(top)}" android:centerColor="{hexc(mid)}" android:endColor="{hexc(bot)}" />
        </aapt:attr>
    </path>
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="54" android:centerY="79.2" android:gradientRadius="50"
                android:startColor="#66FFC88C" android:endColor="#00FFC88C" />
        </aapt:attr>
    </path>
</vector>
''')


def render(px):
    """Full-bleed square PNG for the store (the store applies its own corner mask)."""
    ss = 2
    n = px * ss
    u = n / 512.0
    im = Image.new("RGB", (n, n))
    d = ImageDraw.Draw(im)
    for y in range(n):
        t = y / (n - 1)
        for i in range(len(STOPS) - 1):
            t0, c0 = STOPS[i]; t1, c1 = STOPS[i + 1]
            if t0 <= t <= t1:
                k = (t - t0) / (t1 - t0)
                d.line([(0, y), (n, y)], fill=tuple(int(c0[j] + (c1[j] - c0[j]) * k) for j in range(3)))
                break
    glow = Image.new("L", (n, n), 0)
    r = 0.55 * n
    ImageDraw.Draw(glow).ellipse([n / 2 - r, n - r * 0.35 - r, n / 2 + r, n - r * 0.35 + r], fill=170)
    glow = glow.filter(ImageFilter.GaussianBlur(r * 0.45))
    im = Image.composite(Image.new("RGB", (n, n), (255, 200, 140)), im, glow)

    f, gs, glyphs, s, baseline, bounds, sun = layout()
    # Rasterise the same outlines the app uses, so the PNG and the app icon match exactly.
    from fontTools.pens.recordingPen import RecordingPen
    mask = Image.new("L", (n, n), 0)
    md = ImageDraw.Draw(mask)
    for name, x in glyphs:
        rec = RecordingPen()
        gs[name].draw(TransformPen(rec, (s * u, 0, 0, -s * u, x * u, baseline * u)))
        contour, cur = [], None
        polys = []
        for op, args in rec.value:
            if op == "moveTo":
                cur = [args[0]]
            elif op == "lineTo":
                cur.append(args[0])
            elif op in ("qCurveTo", "curveTo"):
                pts = list(args)
                p0 = cur[-1]
                if op == "qCurveTo":
                    # expand TrueType implied on-curve points
                    on = []
                    for i in range(len(pts) - 1):
                        c = pts[i]
                        nxt = pts[i + 1]
                        end = nxt if i == len(pts) - 2 else ((c[0] + nxt[0]) / 2, (c[1] + nxt[1]) / 2)
                        for t in [j / 12 for j in range(1, 13)]:
                            cur.append(((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * c[0] + t * t * end[0],
                                        (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * c[1] + t * t * end[1]))
                        p0 = end
                else:
                    c1, c2, end = pts
                    for t in [j / 12 for j in range(1, 13)]:
                        a, b2, c3, d3 = (1 - t) ** 3, 3 * (1 - t) ** 2 * t, 3 * (1 - t) * t * t, t ** 3
                        cur.append((a * p0[0] + b2 * c1[0] + c3 * c2[0] + d3 * end[0],
                                    a * p0[1] + b2 * c1[1] + c3 * c2[1] + d3 * end[1]))
            elif op in ("closePath", "endPath"):
                if cur and len(cur) > 2:
                    polys.append(cur)
                cur = None
        # Even-odd fill via XOR so counters (holes) stay open.
        glyph_mask = Image.new("L", (n, n), 0)
        for poly in polys:
            layer = Image.new("L", (n, n), 0)
            ImageDraw.Draw(layer).polygon(poly, fill=255)
            glyph_mask = ImageChops.logical_xor(glyph_mask.convert("1"), layer.convert("1")).convert("L")
        mask = ImageChops.lighter(mask, glyph_mask)
    shadow = mask.filter(ImageFilter.GaussianBlur(0.008 * n)).point(lambda v: int(v * 0.25))
    shadow = ImageChops.offset(shadow, 0, int(0.008 * n * 1.4))
    im.paste((30, 15, 70), (0, 0), shadow)
    im.paste((255, 255, 255), (0, 0), mask)

    # Sun
    cx, cy, rr = sun[0] * u, sun[1] * u, SUN_R * u
    disc = Image.new("RGB", (n, n))
    dd = ImageDraw.Draw(disc)
    for y in range(int(cy - rr), int(cy + rr) + 1):
        t = (y - (cy - rr)) / (2 * rr)
        dd.line([(0, y), (n, y)], fill=(255, int(236 - 66 * t), int(170 - 80 * t)))
    m = Image.new("L", (n, n), 0)
    ImageDraw.Draw(m).ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=255)
    im.paste(disc, (0, 0), m)
    return im.resize((px, px), Image.LANCZOS)


if __name__ == "__main__":
    write_vectors()
    os.makedirs(os.path.join(ROOT, "store"), exist_ok=True)
    for px in (512, 1024, 2048):
        render(px).save(os.path.join(ROOT, "store", f"icon-{px}.png"), optimize=True)
    print("done")
