package com.kodalabs.skydule.icons

import android.app.AlarmManager
import android.app.PendingIntent
import android.content.BroadcastReceiver
import android.content.ComponentName
import android.content.Context
import android.content.Intent
import android.content.pm.PackageManager
import java.time.LocalDate
import java.time.LocalDateTime
import java.time.ZoneId

/** Which launcher icon the user picked in Settings. */
enum class IconChoice(val label: String) {
    DEFAULT("Default"),
    DYNAMIC("Dynamic"),
}

/**
 * The four looks of the dynamic icon's sky. [hour] is the time of day whose sky colours it shows (see
 * tools/generate_day_icons.py PERIOD_HOURS, which must match); [startHour] is when the period begins.
 */
enum class IconPeriod(val label: String, val hour: Float, val startHour: Int) {
    DAWN("Dawn", 6.5f, 5),
    DAY("Day", 11f, 8),
    DUSK("Dusk", 18.5f, 17),
    NIGHT("Night", 22f, 20);

    companion object {
        /** Dawn 05-08, day 08-17, dusk 17-20, night 20-05. */
        fun at(hour: Int): IconPeriod = when (hour) {
            in 5..7 -> DAWN
            in 8..16 -> DAY
            in 17..19 -> DUSK
            else -> NIGHT
        }
    }
}

/**
 * The launcher icon is either the static default or a dynamic one: today's month and day over a sky for the
 * current time of day (dawn, day, dusk, night).
 *
 * Launchers can't draw an icon live, so there is one pre-made activity-alias per (date, period), generated by
 * tools/generate_day_icons.py, plus "DefaultIcon". Exactly one alias is enabled at a time. [apply] switches it;
 * [scheduleNext] plans the next switch (a period boundary or midnight) while Dynamic is chosen.
 */
object DayIcon {
    private const val PREFS = "skydule_day_icon"
    private const val KEY_ACTIVE = "active"
    private const val KEY_CHOICE = "choice"
    /** The alias enabled in the manifest, used until the first [apply]. */
    private const val DEFAULT_ALIAS = "DefaultIcon"
    private const val ALIAS_CLASS_PREFIX = "com.kodalabs.skydule.icons."
    const val ACTION_TICK = "com.kodalabs.skydule.action.ICON_TICK"
    private const val REQUEST_CODE = 0x1c0
    /** Hours at which the period or date changes. */
    private val BOUNDARY_HOURS = listOf(0) + IconPeriod.entries.map { it.startHour }

    /** Alias name for a date and period, e.g. "A1M10D29" for 29 October by day. */
    fun aliasFor(date: LocalDate, period: IconPeriod): String =
        "A%dM%02dD%02d".format(period.ordinal, date.monthValue, date.dayOfMonth)

    fun choice(context: Context): IconChoice =
        runCatching { IconChoice.valueOf(prefs(context).getString(KEY_CHOICE, null) ?: "") }.getOrDefault(IconChoice.DEFAULT)

    /** True while the app is on screen. Switching the launcher alias then would close it, so switches wait. */
    @Volatile var appVisible = false

    /**
     * Saves the choice. The launcher icon itself changes the next time the app goes out of sight (MainActivity.onStop),
     * because switching the alias the app was launched from closes the running app.
     */
    fun setChoice(context: Context, choice: IconChoice) {
        prefs(context).edit().putString(KEY_CHOICE, choice.name).apply()
        scheduleNext(context)
    }

    /** Switches the launcher icon to match the choice and [now]. Cheap, so it's safe to call often. */
    fun apply(context: Context, now: LocalDateTime = LocalDateTime.now()) {
        val prefs = prefs(context)
        val target = when (choice(context)) {
            IconChoice.DEFAULT -> DEFAULT_ALIAS
            IconChoice.DYNAMIC -> aliasFor(now.toLocalDate(), IconPeriod.at(now.hour))
        }
        val recorded = prefs.getString(KEY_ACTIVE, DEFAULT_ALIAS) ?: DEFAULT_ALIAS
        // Trust the package manager, not just our note: the note can be stale (data cleared, interrupted switch).
        val targetOn = isEnabled(context, target)
        if (targetOn && recorded == target && (target == DEFAULT_ALIAS || !isEnabled(context, DEFAULT_ALIAS))) return
        // Enable the new icon before disabling the old ones, so the launcher never loses the app.
        if (!targetOn) setEnabled(context, target, true)
        for (old in setOf(recorded, DEFAULT_ALIAS)) {
            if (old != target && isEnabled(context, old)) setEnabled(context, old, false)
        }
        prefs.edit().putString(KEY_ACTIVE, target).apply()
    }

    /** Plans the next switch for the coming period boundary or midnight. Does nothing for the default icon. */
    fun scheduleNext(context: Context, now: LocalDateTime = LocalDateTime.now()) {
        val alarms = context.getSystemService(AlarmManager::class.java)
        val intent = Intent(context, DayIconReceiver::class.java).setAction(ACTION_TICK)
        val pi = PendingIntent.getBroadcast(
            context,
            REQUEST_CODE,
            intent,
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE,
        )
        if (choice(context) != IconChoice.DYNAMIC) {
            alarms.cancel(pi)
            return
        }
        val nextHour = BOUNDARY_HOURS.firstOrNull { it > now.hour }
        val next = if (nextHour != null) now.toLocalDate().atTime(nextHour, 0) else now.toLocalDate().plusDays(1).atStartOfDay()
        val at = next.plusSeconds(5).atZone(ZoneId.systemDefault()).toInstant().toEpochMilli()
        // Inexact is fine here: a switch a few minutes late is invisible, and it avoids exact-alarm permission.
        alarms.setAndAllowWhileIdle(AlarmManager.RTC_WAKEUP, at, pi)
    }

    private fun prefs(context: Context) = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)

    /** Aliases are disabled in the manifest except [DEFAULT_ALIAS], so "default" only counts as on for that one. */
    private fun isEnabled(context: Context, alias: String): Boolean =
        when (context.packageManager.getComponentEnabledSetting(ComponentName(context, ALIAS_CLASS_PREFIX + alias))) {
            PackageManager.COMPONENT_ENABLED_STATE_ENABLED -> true
            PackageManager.COMPONENT_ENABLED_STATE_DEFAULT -> alias == DEFAULT_ALIAS
            else -> false
        }

    private fun setEnabled(context: Context, alias: String, enabled: Boolean) {
        context.packageManager.setComponentEnabledSetting(
            ComponentName(context, ALIAS_CLASS_PREFIX + alias),
            if (enabled) PackageManager.COMPONENT_ENABLED_STATE_ENABLED else PackageManager.COMPONENT_ENABLED_STATE_DISABLED,
            // Don't kill the app process when the launcher alias changes.
            PackageManager.DONT_KILL_APP,
        )
    }
}

/** Runs at each period change and midnight, after boot, after a time-zone or clock change, and after an app update. */
class DayIconReceiver : BroadcastReceiver() {
    override fun onReceive(context: Context, intent: Intent) {
        // If the app is open, leave it alone: it applies the change itself when it goes out of sight.
        if (!DayIcon.appVisible) DayIcon.apply(context)
        DayIcon.scheduleNext(context)
    }
}
